package com.mat.entity;

/**
 * entity package
 *
 * This package will contain JPA Entity classes.
 * Each entity class maps directly to a database table.
 *
 * Examples of future entities:
 *   - User        → maps to the 'users' table
 *   - Asset       → maps to the 'assets' table
 *   - Assignment  → maps to the 'assignments' table
 *
 * Entities are annotated with:
 *   @Entity     - marks the class as a JPA entity
 *   @Table      - specifies the table name
 *   @Id         - marks the primary key field
 *   @Column     - customizes column mapping
 */
